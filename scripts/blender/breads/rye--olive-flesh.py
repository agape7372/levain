"""올리브 호밀빵 (rye--olive-flesh) — 형상 · 껍질은 rye_kit.build_rye, 단면은 rye_kit.crumb.

실물: 네이버 이미지 「올리브 호밀빵」(2026-11-16) — 대표 모습이 썬 단면: 회갈색 호밀 속살에 검정 · 올리브그린 올리브가 고리 · 반달 · 통알로 박힌다. 겉은 보통 호밀빵.
구성: 왼끝을 살짝 위로 비스듬히 썬 단면 · 회갈 속살 + 크기 섞인 올리브(검정 고리 · 반달, 초록 고리 · 통알, 윤기) · 기름이 살짝 밴 번짐.
"""
import rye_kit as rk

# (u, v, 반지름, 각°, 길쭉함, 구멍 비, 반달) — 단면 (y, z). 크기 · 방향을 흩고 나란한 둘이 없게
# 반달 고리(구멍 + 반쪽)는 눈썹 · 입으로 읽혀 단면이 얼굴이 됐다(r2) — 반달은 속이 찬 반쪽으로, 수를 늘려 배치를 흩는다
BLACK = [(-0.13, 0.08, 0.042, 20, 1.2, 0.45, 0), (0.04, 0.065, 0.032, 70, 1.25, 0, 0),
         (-0.03, 0.195, 0.034, -15, 1.2, 0.42, 0), (0.16, 0.165, 0.026, 80, 1.2, 0.4, 0), (0.1, 0.21, 0.02, 30, 1.3, 0, 0)]
GREEN = [(0.14, 0.075, 0.036, -35, 1.2, 0.42, 0), (-0.075, 0.14, 0.022, 40, 1.3, 0, 0),
         (0.05, 0.145, 0.028, 0, 1.25, 0, -1), (-0.17, 0.17, 0.022, 70, 1.2, 0.4, 0)]


def crumb(lib):
    return rk.crumb(lib, fills=[
        dict(mask=rk.bits(BLACK), col=('#1C1216', '#2E2028'), halo=('#6E5A4A', 0.3), gloss=0.38),
        dict(mask=rk.bits(GREEN), col=('#4C4824', '#625C2E'), halo=('#7A6A4C', 0.3), gloss=0.38)])


def build(lib):
    return rk.build_rye(lib, seed=41, cut=('end', -0.3, (-1, -0.3, 0.3)), crumb=crumb, opts=dict(uv_weight={'crumb': 1.8}))
