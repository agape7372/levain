"""건포도 호밀빵 (rye--raisin-flesh) — 형상 · 껍질은 rye_kit.build_rye, 단면은 rye_kit.crumb.

실물: 네이버 이미지 「건포도 호밀빵」(2026-11-16) — 대표 모습이 썬 단면: 회갈 속살에 쭈글한 적갈색 건포도가 반죽 결을 따라 몇 알씩 몰려 박힌다. 겉은 보통 호밀빵, 군데군데 건포도가 껍질에 비친다.
구성: 왼끝을 길게 비스듬히 썬 단면 · 회갈 속살 + 결 따라 몰린 길쭉하고 쭈글한 건포도 무리(자갈색 · 밝은 주름 · 옅은 번짐).
"""
import rye_kit as rk

# 무리 셋 — 결(사선) 따라 2~4알씩, 크기 · 방향 흩음
RAISIN = [(-0.13, 0.065, 0.024, 25, 1.8, 0, 0), (-0.08, 0.1, 0.018, 40, 2.0, 0, 0), (-0.16, 0.12, 0.015, 10, 1.7, 0, 0),
          (0.04, 0.165, 0.022, -20, 1.9, 0, 0), (0.09, 0.14, 0.017, -35, 1.8, 0, 0),
          (0.12, 0.055, 0.02, 60, 1.8, 0, 0), (0.17, 0.09, 0.014, 45, 2.1, 0, 0), (-0.02, 0.05, 0.015, 15, 1.7, 0, 0)]


def crumb(lib):
    r = rk.bits(RAISIN, warp=0.5)
    return rk.crumb(lib, fills=[
        dict(mask=r, col=('#2E100A', '#40160E'), halo=('#4A362A', 0.4), gloss=0.42),
        dict(mask=rk.veined(r, scale=28, width=0.06), col=('#5A2A1A', '#64301E'), gloss=0.42)])


def build(lib):
    return rk.build_rye(lib, seed=59, cut=('end', -0.24, (-1, -0.9, 0.1)), crumb=crumb,
                        opts=dict(uv_weight={'crumb': 1.8}))
